/**
 * Манифест строк — канал между сборкой и генератором точки входа приложения.
 *
 * Та же природа, что у манифеста тем, но разрыв другой. Приложение объявляет
 * состав пакетов ровно один раз — в `providers` конфига UnoCSS. Какие из них
 * несут строки, по каким подпутям и на каких языках, знает только сборка, а
 * нужно это тому, кто пишет `createFintI18n({ loaders })`. Без канала список
 * пакетов дублируется вторым реестром и молча расходится с первым при появлении
 * нового спутника.
 *
 * Здесь только **адреса и состав**: пресет не импортирует лоадеры и не знает
 * ни имён блоков, ни формата i18n-рантайма. Импорты пишет потребитель — он
 * один знает, чем собирает.
 *
 * Модуль browser-safe: только типы, ни FS, ни исполняемого кода. Правило
 * подбора локали жить здесь не должно и не живёт — оно посчитано на сборке
 * (`core/i18nLocales`), а сюда доезжает готовым результатом.
 */

/**
 * Одна связка: что импортировать и какие запрошенные теги это покрывает.
 *
 * Связка существует потому, что «что просило приложение» и «что импортировать»
 * — разные строки, и плоский список локалей не мог быть и тем и другим сразу:
 * `pt-BR` не идентификатор, а `ru-RU` может обслуживаться лоадерами `ru`.
 */
export interface GranularI18nBinding {
  /** Объявленный пакетом тег — он же верхний ключ `LocaleLoaderCollection`. */
  locale: string
  /** Имя именованного экспорта в `entry`: для `pt-BR` это `ptBR`. */
  exportName: string
  /**
   * Запрошенные приложением теги, которые обслуживает эта связка.
   *
   * Их может быть несколько: если приложение везёт `ru` и `ru-RU`, а пакет
   * объявил только `ru`, оба покрываются ОДНИМ импортом.
   */
  serves: readonly string[]
  /**
   * Каким шагом каскада связка найдена.
   *
   * `region` означает обратный шаг — запрошен `ru`, а пакет отдаёт `ru-RU`.
   * Стоит показать это вслух: приложению придётся выставить локаль в самый
   * специфичный тег, иначе `fint-i18n` до этих лоадеров не дойдёт (обход
   * `parent → child` он не делает).
   */
  via: 'exact' | 'base' | 'region'
}

/** Вклад одного пакета. */
export interface GranularI18nEntry {
  /** `id` провайдера, он же имя npm-пакета по конвенции. */
  providerId: string
  /** Подпуть с именованными per-locale экспортами (дефолт уже подставлен). */
  entry: string
  /** Подпуть-агрегат: default-экспорт МАССИВА коллекций (дефолт подставлен). */
  allEntry: string
  /** Всё, что пакет объявил, — независимо от запроса приложения. */
  locales: readonly string[]
  /**
   * Что импортировать после пересечения с запрошенным приложением.
   *
   * Пусто означает, что пакет не может обслужить ни один запрошенный язык, —
   * генератору тут импортировать нечего, а потребителю стоит сказать об этом
   * вслух: молча пропущенный пакет выглядит как «строки не работают».
   */
  bindings: readonly GranularI18nBinding[]
}

export interface GranularI18nManifest {
  /** Вклады в порядке резолюции провайдеров: доноры раньше зависимых. */
  entries: readonly GranularI18nEntry[]
  /**
   * Объединение `binding.locale` без повторов — то, что уедет в бандл.
   *
   * Это ОБЪЯВЛЕННЫЕ теги, а не запрошенные: при запросе `ru-RU` и пакете с
   * `ru` здесь будет `ru`. Именно в таком виде список нужен `negotiateLocale`
   * как `available` — он же результат `getAvailableLocales()` в рантайме.
   */
  locales: readonly string[]
  /**
   * Запрошенные теги, которых не обслуживает ни один пакет.
   *
   * Единственное место, где такой промах вообще виден: в рантайме
   * `negotiateLocale` молча свалится в `fallbackLocale`.
   */
  unserved: readonly string[]
}
